"""Bake the OIT font atlas: Manrope (UI) and JetBrains Mono (data), both SIL OFL 1.1, at the pixel sizes the
OIT pages use, into one 8-bit alpha atlas plus per-glyph metrics, written as a C header (oit_font.h) that the
plugin compiles in, and a JSON copy of the metrics for the offline page renderer.

Usage: make_font.py <fonts dir with Manrope-*.ttf and JetBrainsMono-Regular.ttf> <out dir>
"""
import json, os, sys
from PIL import Image, ImageDraw, ImageFont

FACES = [  # (id, file, pixel size)
    ('ui14', 'Manrope-Medium.ttf', 14), ('ui16', 'Manrope-Medium.ttf', 16), ('ui18', 'Manrope-Medium.ttf', 18),
    ('ui20', 'Manrope-Medium.ttf', 20), ('ui24', 'Manrope-Medium.ttf', 24), ('ui30', 'Manrope-Medium.ttf', 30),
    ('bold16', 'Manrope-Bold.ttf', 16), ('bold18', 'Manrope-Bold.ttf', 18), ('bold20', 'Manrope-Bold.ttf', 20),
    ('bold24', 'Manrope-Bold.ttf', 24), ('bold30', 'Manrope-Bold.ttf', 30), ('bold40', 'Manrope-Bold.ttf', 40),
    ('mono16', 'JetBrainsMono-Regular.ttf', 16), ('mono18', 'JetBrainsMono-Regular.ttf', 18),
    ('mono20', 'JetBrainsMono-Regular.ttf', 20), ('mono24', 'JetBrainsMono-Regular.ttf', 24),
]
# ASCII plus a few symbols, remapped to bytes 128.. so page code can use single-byte strings.
EXTRA = {128: '°', 129: '▲', 130: '▼', 131: '◀', 132: '▶', 133: '✓', 134: '•',
         135: '→', 136: '←', 137: '·'}
FALLBACK = {129, 130, 131, 132, 133}
CHARS = [(c, chr(c)) for c in range(32, 127)] + sorted(EXTRA.items())
ATLAS_W = 1024


def main(font_dir, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    glyphs, faces = [], []
    x = y = 1
    row_h = 0
    sheet = Image.new('L', (ATLAS_W, 2048), 0)
    for fid, fname, size in FACES:
        path = os.path.join(font_dir, fname)
        main_font = ImageFont.truetype(path, size)
        mono = ImageFont.truetype(os.path.join(font_dir, 'JetBrainsMono-Regular.ttf'), size)
        ascent, descent = main_font.getmetrics()
        first = len(glyphs)
        for code, ch in CHARS:
            font = mono if code in FALLBACK else main_font   # Manrope has no arrows/check: JetBrains Mono
            try:
                l, t, r, b = font.getbbox(ch)
            except Exception:
                l = t = r = b = 0
            adv = font.getlength(ch)
            w, h = max(0, r - l), max(0, b - t)
            if ch != ' ' and w and h:
                if x + w + 2 > ATLAS_W:
                    x, y, row_h = 1, y + row_h + 2, 0
                ImageDraw.Draw(sheet).text((x - l, y - t), ch, font=font, fill=255)
                gx, gy = x, y
                x += w + 2
                row_h = max(row_h, h)
            else:
                gx = gy = w = h = 0
            # xoff/yoff: glyph box relative to the pen (baseline at y = ascent below the line top)
            glyphs.append((code, gx, gy, w, h, l, t, round(adv * 64)))
        faces.append((fid, size, ascent, descent, first))
    used_h = y + row_h + 2
    atlas_h = 1
    while atlas_h < used_h:
        atlas_h *= 2
    sheet = sheet.crop((0, 0, ATLAS_W, atlas_h))
    # 4x4 opaque block in the bottom-right corner: solid shapes sample its centre (one GL state for everything)
    ImageDraw.Draw(sheet).rectangle((ATLAS_W - 4, atlas_h - 4, ATLAS_W - 1, atlas_h - 1), fill=255)
    sheet.save(os.path.join(out_dir, 'oit_font_atlas.png'))
    data = sheet.tobytes()
    with open(os.path.join(out_dir, 'oit_font.h'), 'w') as f:
        f.write('/* Generated by tools/make_font.py - do not edit. Manrope and JetBrains Mono: SIL Open Font '
                'License 1.1 (fonts/OFL.txt). */\n#pragma once\n')
        f.write(f'#define OIT_ATLAS_W {ATLAS_W}\n#define OIT_ATLAS_H {atlas_h}\n#define OIT_GLYPHS_PER_FACE {len(CHARS)}\n')
        f.write(f'#define OIT_WHITE_U {(ATLAS_W - 2) / ATLAS_W:.8f}f\n#define OIT_WHITE_V {(atlas_h - 2) / atlas_h:.8f}f\n')
        f.write('typedef struct { unsigned char code; short x, y, w, h, xoff, yoff; int adv64; } OitGlyph;\n')
        f.write('typedef struct { const char *id; int size, ascent, descent, first; } OitFace;\n')
        f.write('enum {' + ', '.join(f'OIT_F_{fid.upper()}' for fid, *_ in faces) + ', OIT_F_COUNT};\n')
        f.write('static const OitFace oit_faces[OIT_F_COUNT] = {\n')
        for fid, size, asc, desc, first in faces:
            f.write(f'    {{"{fid}", {size}, {asc}, {desc}, {first}}},\n')
        f.write('};\nstatic const OitGlyph oit_glyphs[] = {\n')
        for g in glyphs:
            f.write('    {%d, %d, %d, %d, %d, %d, %d, %d},\n' % g)
        f.write('};\nstatic const unsigned char oit_atlas[OIT_ATLAS_W * OIT_ATLAS_H] = {\n')
        for i in range(0, len(data), 32):
            f.write(','.join(str(b) for b in data[i:i + 32]) + ',\n')
        f.write('};\n')
    json.dump({'atlas': [ATLAS_W, atlas_h], 'faces': faces, 'glyphs': glyphs},
              open(os.path.join(out_dir, 'oit_font.json'), 'w'))
    print(f'atlas {ATLAS_W}x{atlas_h} ({used_h} rows used), {len(faces)} faces, {len(glyphs)} glyphs')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
